/**
 * Dark-theme guard generator.
 *
 * Scans every stylesheet declaration and every hex colour used inside JSX inline styles,
 * and emits `src/styles/theme-guard.generated.css` which re-maps hardcoded light backgrounds,
 * dark text and light borders to the active theme tokens ONLY when data-app-theme="dark".
 *
 * Run:  node scripts/gen-dark-guard.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const SRC = path.resolve('src');
const OUT = path.join(SRC, 'styles', 'theme-guard.generated.css');
const CSS_FILES = ['index.css', 'App.css'].map((f) => path.join(SRC, f));
const SKIP_SELECTOR = /invoice|receipt|print|paper|landing|login|register|auth-|knob|thumb|toggle|switch|slider|checkbox|radio|spinner|skeleton|:root|^html|^body|keep-light|swatch|theme-card|theme-preview/i;
const SKIP_JSX = /LandingPage|Login\.jsx|Register\.jsx/;
const DARK = 'html[data-app-theme="dark"]';
const NOT_PRINT =
  ':not(:is(.invoice-print,.receipt-print,.print-paper,.invoice-preview-container,.invoice-sheet,.receipt-sheet,[data-theme-ignore="true"],.keep-light) *)';

/* ---------- colour helpers ---------- */
function parseColor(raw) {
  const v = raw.trim().toLowerCase();
  if (v === 'white') return { r: 255, g: 255, b: 255, a: 1 };
  if (v === 'black') return { r: 0, g: 0, b: 0, a: 1 };
  let m = v.match(/^#([0-9a-f]{3,8})$/);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = h.split('').map((c) => c + c).join('');
    if (h.length !== 6 && h.length !== 8) return null;
    return {
      r: parseInt(h.slice(0, 2), 16),
      g: parseInt(h.slice(2, 4), 16),
      b: parseInt(h.slice(4, 6), 16),
      a: h.length === 8 ? parseInt(h.slice(6, 8), 16) / 255 : 1,
    };
  }
  m = v.match(/^rgba?\(\s*(\d+)[\s,]+(\d+)[\s,]+(\d+)(?:[\s,/]+([\d.]+))?\s*\)$/);
  if (m) return { r: +m[1], g: +m[2], b: +m[3], a: m[4] !== undefined ? +m[4] : 1 };
  return null;
}
function toHsl({ r, g, b }) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0, s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  return { h, s, l };
}
const isNeutral = (c) => Math.max(c.r, c.g, c.b) - Math.min(c.r, c.g, c.b) < 24;

/* ---------- mapping (dark theme) ---------- */
function mapBg(c) {
  if (c.a < 0.9) return null;
  const { h, l } = toHsl(c);
  if (l >= 0.985) return 'var(--bg-card)';
  if (isNeutral(c) && l >= 0.86) return 'var(--hover-bg)';
  if (!isNeutral(c) && l >= 0.84) return `hsla(${Math.round(h)}, 70%, 50%, 0.15)`;
  return null;
}
function mapText(c) {
  if (c.a < 0.9) return null;
  const { h, s, l } = toHsl(c);
  if (isNeutral(c)) {
    if (l <= 0.3) return 'var(--text-title)';
    if (l <= 0.46) return 'var(--text-table)';
    return null;
  }
  if (l <= 0.45) return `hsl(${Math.round(h)}, ${Math.round(Math.min(s, 0.85) * 100)}%, 72%)`;
  return null;
}
function mapBorder(c) {
  if (c.a < 0.9) return null;
  const { h, l } = toHsl(c);
  if (isNeutral(c) && l >= 0.7) return 'var(--border)';
  if (!isNeutral(c) && l >= 0.8) return `hsla(${Math.round(h)}, 70%, 50%, 0.35)`;
  return null;
}

const COLOR_RE = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b/g;
function mapValue(prop, value) {
  if (/gradient|url\(/i.test(value) || /var\(/i.test(value)) return null;
  const p = prop.toLowerCase();
  if (p === 'background' || p === 'background-color') {
    const c = parseColor(value.replace(/\s*!important/i, ''));
    const mapped = c && mapBg(c);
    return mapped || null;
  }
  if (p === 'color') {
    const c = parseColor(value.replace(/\s*!important/i, ''));
    const mapped = c && mapText(c);
    return mapped || null;
  }
  if (/^border(-(top|right|bottom|left))?(-color)?$/.test(p) || p === 'outline-color') {
    let changed = false;
    const out = value.replace(COLOR_RE, (tok) => {
      const c = parseColor(tok);
      const mapped = c && mapBorder(c);
      if (mapped) { changed = true; return mapped; }
      return tok;
    });
    return changed ? out.replace(/\s*!important/i, '') : null;
  }
  return null;
}

/* ---------- 1. stylesheet rules ---------- */
const out = [
  '/* AUTO-GENERATED by scripts/gen-dark-guard.mjs — do not edit by hand. */',
  '/* Re-maps hardcoded light backgrounds / dark text / light borders to theme tokens in Midnight Dark. */',
];
let ruleCount = 0;
for (const file of CSS_FILES) {
  const root = postcss.parse(fs.readFileSync(file, 'utf8'));
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes|print/i.test(rule.parent.name + ' ' + rule.parent.params)) return;
    if (rule.parent && rule.parent.type === 'atrule' && rule.parent.name === 'media' && /print/i.test(rule.parent.params)) return;
    const selectors = rule.selectors.filter((s) => !SKIP_SELECTOR.test(s) && !/^(\d+%|from|to)$/.test(s.trim()));
    if (!selectors.length) return;
    const decls = [];
    rule.walkDecls((d) => {
      const mapped = mapValue(d.prop, d.value);
      if (mapped) decls.push(`${d.prop.toLowerCase() === 'background' ? 'background-color' : d.prop}: ${mapped} !important;`);
    });
    if (!decls.length) return;
    const sel = selectors.map((s) => `${DARK} ${s}`).join(',\n');
    let block = `${sel} {\n  ${decls.join('\n  ')}\n}`;
    const parent = rule.parent;
    if (parent && parent.type === 'atrule' && parent.name === 'media') block = `@media ${parent.params} {\n${block}\n}`;
    out.push(block);
    ruleCount++;
  });
}

/* ---------- 2. inline styles in JSX ---------- */
function walk(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (/\.jsx$/.test(e.name) && !SKIP_JSX.test(p)) acc.push(p);
  }
  return acc;
}
const hexes = new Set();
for (const f of walk(SRC)) {
  const text = fs.readFileSync(f, 'utf8');
  for (const m of text.matchAll(/['"`](#[0-9a-fA-F]{3,8})['"`]/g)) hexes.add(m[1].toLowerCase());
  for (const m of text.matchAll(/['"`](rgba?\([^'"`]*\))['"`]/g)) hexes.add(m[1].toLowerCase());
}
const rgbStr = (c) => `rgb(${c.r}, ${c.g}, ${c.b})`;
const seen = new Set();
let inlineCount = 0;
out.push('\n/* ===== Inline style guard (React inline hardcoded colours) ===== */');
for (const hx of hexes) {
  const c = parseColor(hx);
  if (!c || c.a < 0.9) continue;
  const rgb = rgbStr(c);
  if (seen.has(rgb)) continue;
  seen.add(rgb);
  const bg = mapBg(c), tx = mapText(c), bd = mapBorder(c);
  if (bg) {
    out.push(
      `${DARK} [style*="background: ${rgb}"]${NOT_PRINT},\n${DARK} [style*="background-color: ${rgb}"]${NOT_PRINT} { background: ${bg} !important; }`
    );
    inlineCount++;
  }
  if (tx) {
    out.push(
      `${DARK} [style^="color: ${rgb}"]${NOT_PRINT},\n${DARK} [style*="; color: ${rgb}"]${NOT_PRINT} { color: ${tx} !important; }`
    );
    inlineCount++;
  }
  if (bd) {
    out.push(`${DARK} [style*="solid ${rgb}"]${NOT_PRINT} { border-color: ${bd} !important; }`);
    inlineCount++;
  }
}

fs.writeFileSync(OUT, out.join('\n\n') + '\n');
console.log(`Generated ${OUT}\n  stylesheet rules: ${ruleCount}\n  inline rules: ${inlineCount}\n  unique inline colours scanned: ${hexes.size}`);
